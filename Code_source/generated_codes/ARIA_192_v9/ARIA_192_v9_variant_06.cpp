// ------------------------------------------------------------
//  Helper: XOR two vectors (state ^= roundKey)
// ------------------------------------------------------------
void addRoundKey(std::vector<int>& state, const std::vector<int>& rkey) {
    for (int i = 0; i < 16; ++i) {
        state[i] ^= rkey[i];
    }
}

// ------------------------------------------------------------
//  Helper: Substitution layer (uses SB1 or SB2)
// ------------------------------------------------------------
void subLayer(const std::vector<int>& src, std::vector<int>& dst, bool useSB1) {
    for (int i = 0; i < 16; ++i) {
        int val = src[i];
        dst[i] = useSB1 ? sbox1[val] : sbox2[val];
    }
}

// ------------------------------------------------------------
//  Helper: Diffusion layer (M)
//  The matrix multiplication is performed via a fixed
//  sequence of XORs as defined in the ARIA spec.
// ------------------------------------------------------------
void diffuse(const std::vector<int>& src, std::vector<int>& dst) {
    // split the 16‑byte state into four 4‑byte words
    int w0 = (src[0] << 24) | (src[1] << 16) | (src[2] << 8) | src[3];
    int w1 = (src[4] << 24) | (src[5] << 16) | (src[6] << 8) | src[7];
    int w2 = (src[8] << 24) | (src[9] << 16) | (src[10] << 8) | src[11];
    int w3 = (src[12] << 24) | (src[13] << 16) | (src[14] << 8) | src[15];

    // Apply the linear transformation (M)
    int t0 = w0 ^ w1;
    int t1 = w2 ^ w3;
    int t2 = w0 ^ w2;
    int t3 = w1 ^ w3;

    // Re‑assemble bytes
    dst[0]  = (t0 >> 24) & 0xff; dst[1]  = (t0 >> 16) & 0xff;
    dst[2]  = (t0 >> 8)  & 0xff; dst[3]  =  t0        & 0xff;
    dst[4]  = (t1 >> 24) & 0xff; dst[5]  = (t1 >> 16) & 0xff;
    dst[6]  = (t1 >> 8)  & 0xff; dst[7]  =  t1        & 0xff;
    dst[8]  = (t2 >> 24) & 0xff; dst[9]  = (t2 >> 16) & 0xff;
    dst[10] = (t2 >> 8)  & 0xff; dst[11] =  t2        & 0xff;
    dst[12] = (t3 >> 24) & 0xff; dst[13] = (t3 >> 16) & 0xff;
    dst[14] = (t3 >> 8)  & 0xff; dst[15] =  t3        & 0xff;
}

// ------------------------------------------------------------
//  Helper: Rotate a 16‑byte vector left by n bytes
// ------------------------------------------------------------
std::vector<int> rotateLeft(const std::vector<int>& in, int n) {
    std::vector<int> out(16);
    for (int i = 0; i < 16; ++i) {
        out[i] = in[(i + n) % 16];
    }
    return out;
}

// ------------------------------------------------------------
//  Key schedule for ARIA‑192
//  Produces 15 round keys (K0 … K14)
// ------------------------------------------------------------
void expandKey(const std::vector<int>& master, std::vector< std::vector<int> >& rkeys) {
    // Constants C1‑C4 (only the first 16 bytes are needed)
    int constC[4][16] = {
        {0x51,0x7c,0x4c,0x73,0x4d,0xb5,0x5e,0x2e,0x99,0x9a,0x80,0x61,0x71,0x61,0x7e,0x5a},
        {0x00,0xd5,0xe4,0x20,0x5c,0x7c,0x36,0x3b,0xb1,0xe4,0x73,0x8b,0x2f,0x88,0x43,0x6c},
        {0x5c,0x5e,0x1b,0x42,0x9a,0x01,0x00,0x5d,0x89,0x2c,0xc2,0x1e,0xc9,0x6c,0x08,0x9c},
        {0x15,0x30,0x5a,0x51,0x5b,0x2b,0x33,0x63,0x30,0xd6,0x0e,0x64,0x2a,0x0a,0x79,0x68}
    };

    // Step 1: generate three intermediate keys K0, K1, K2
    std::vector<int> tmp1(16), tmp2(16), tmp3(16);
    subLayer(master, tmp1, true);          // SL1
    addRoundKey(tmp1, std::vector<int>(constC[0], constC[0] + 16));
    diffuse(tmp1, tmp2);                   // M
    subLayer(tmp2, tmp3, false);           // SL2
    addRoundKey(tmp3, std::vector<int>(constC[1], constC[1] + 16));
    std::vector<int> k0 = tmp3;            // first 128‑bit subkey

    // Derive K1
    subLayer(k0, tmp1, true);
    addRoundKey(tmp1, std::vector<int>(constC[2], constC[2] + 16));
    diffuse(tmp1, tmp2);
    subLayer(tmp2, tmp3, false);
    addRoundKey(tmp3, std::vector<int>(constC[3], constC[3] + 16));
    std::vector<int> k1 = tmp3;            // second subkey

    // Derive K2 (uses the remaining master‑key bytes)
    std::vector<int> mkTail(8);
    for (int i = 0; i < 8; ++i) mkTail[i] = master[16 + i];
    std::vector<int> combined(16);
    for (int i = 0; i < 8; ++i) combined[i] = k1[i];
    for (int i = 0; i < 8; ++i) combined[8 + i] = mkTail[i];
    subLayer(combined, tmp1, true);
    addRoundKey(tmp1, std::vector<int>(constC[0], constC[0] + 16));
    diffuse(tmp1, tmp2);
    subLayer(tmp2, tmp3, false);
    addRoundKey(tmp3, std::vector<int>(constC[1], constC[1] + 16));
    std::vector<int> k2 = tmp3;            // third subkey

    // ------------------------------------------------------------
    //  Build round keys by rotating K0, K1, K2
    // ------------------------------------------------------------
    rkeys.resize(15);
    rkeys[0] = rotateLeft(k0, 0);
    rkeys[1] = rotateLeft(k1, 1);
    rkeys[2] = rotateLeft(k2, 2);
    rkeys[3] = rotateLeft(k0, 3);
    rkeys[4] = rotateLeft(k1, 4);
    rkeys[5] = rotateLeft(k2, 5);
    rkeys[6] = rotateLeft(k0, 6);
    rkeys[7] = rotateLeft(k1, 7);
    rkeys[8] = rotateLeft(k2, 8);
    rkeys[9] = rotateLeft(k0, 9);
    rkeys[10]= rotateLeft(k1,10);
    rkeys[11]= rotateLeft(k2,11);
    rkeys[12]= rotateLeft(k0,12);
    rkeys[13]= rotateLeft(k1,13);
    rkeys[14]= rotateLeft(k2,14);
}

// ------------------------------------------------------------
//  Encryption of a single 16‑byte block with ARIA‑192
// ------------------------------------------------------------
void encryptBlock(const std::vector<int>& plain,
                  const std::vector< std::vector<int> >& rkeys,
                  std::vector<int>& cipher) {
    std::vector<int> state = plain;
    std::vector<int> tmp(16);
    // 14 rounds (since key size is 192‑bit)
    for (int round = 0; round < 14; ++round) {
        bool useFirst = (round % 2 == 0);
        subLayer(state, tmp, useFirst);   // SL1 or SL2
        diffuse(tmp, state);              // M
        addRoundKey(state, rkeys[round + 1]);
    }
    // Final round: only substitution + final key XOR
    bool finalFirst = (14 % 2 == 0);
    subLayer(state, tmp, finalFirst);
    addRoundKey(tmp, rkeys[14]);
    cipher = tmp;
}

// ------------------------------------------------------------
//  Utility: print a 16‑byte vector as hex
// ------------------------------------------------------------
void printHex(const std::vector<int>& data) {
    for (int i = 0; i < 16; ++i) {
        std::cout << std::hex << std::setw(2) << std::setfill('0')
                  << (data[i] & 0xff);
    }
    std::cout << std::dec << std::endl;
}

// ------------------------------------------------------------
//  Main – uses ordered, structured test vectors
// ------------------------------------------------------------
int main() {
    // Structured plaintext 1: ascending bytes 0x00..0x0F
    std::vector<int> ptAsc(16);
    for (int i = 0; i < 16; ++i) ptAsc[i] = i;

    // Structured key 1: ascending bytes 0x00..0x17 (24 bytes)
    std::vector<int> keyAsc(24);
    for (int i = 0; i < 24; ++i) keyAsc[i] = i;

    // Structured plaintext 2: descending bytes 0x0F..0x00
    std::vector<int> ptDesc(16);
    for (int i = 0; i < 16; ++i) ptDesc[i] = 15 - i;

    // Structured key 2: descending bytes 0xFF..0xE8
    std::vector<int> keyDesc(24);
    for (int i = 0; i < 24; ++i) keyDesc[i] = 0xFF - i;

    // Expand both keys
    std::vector< std::vector<int> > roundKeysAsc;
    std::vector< std::vector<int> > roundKeysDesc;
    expandKey(keyAsc, roundKeysAsc);
    expandKey(keyDesc, roundKeysDesc);

    // Encrypt both blocks
    std::vector<int> ctAsc, ctDesc;
    encryptBlock(ptAsc, roundKeysAsc, ctAsc);
    encryptBlock(ptDesc, roundKeysDesc, ctDesc);

    // Output
    std::cout << "Ciphertext (ascending input): ";
    printHex(ctAsc);
    std::cout << "Ciphertext (descending input): ";
    printHex(ctDesc);

    return 0;
}
