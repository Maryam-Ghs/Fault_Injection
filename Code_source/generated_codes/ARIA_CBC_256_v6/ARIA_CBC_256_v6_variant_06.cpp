/* ---------------------------------------------------------------- *
 *  Helper: print a vector of bytes as hex.
 * ---------------------------------------------------------------- */
void printHex(const std::vector<int>& data, const char* title)
{
    std::cout << title;
    for (int i = 0; i < (int)data.size(); ++i)
    {
        std::cout << std::hex << std::setw(2) << std::setfill('0') << (data[i] & 0xFF);
        if ((i + 1) % 16 == 0) std::cout << '\n';
        else std::cout << ' ';
    }
    std::cout << std::dec << std::endl;
}

/* ---------------------------------------------------------------- *
 *  Substitution layer – choose S‑box 1 or S‑box 2.
 * ---------------------------------------------------------------- */
void substitute(std::vector<int>& state, int useS1)
{
    for (int i = 0; i < 16; ++i)
    {
        int byte = state[i] & 0xFF;
        if (useS1)
            state[i] = S1[byte];
        else
            state[i] = S2[byte];
    }
}

/* ---------------------------------------------------------------- *
 *  Diffusion layer – a very simple mixing operation.
 *  (Real ARIA uses a more complex linear transform.)
 * ---------------------------------------------------------------- */
void diffuse(std::vector<int>& state)
{
    std::vector<int> tmp(16);
    for (int i = 0; i < 16; ++i)
    {
        int a = state[i];
        int b = state[(i + 1) % 16];
        tmp[i] = a ^ b;                     // XOR with neighbour
    }
    for (int i = 0; i < 16; ++i) state[i] = tmp[i];
}

/* ---------------------------------------------------------------- *
 *  Add round key – XOR the 16‑byte round key into the state.
 * ---------------------------------------------------------------- */
void addRoundKey(std::vector<int>& state, const std::vector<int>& rk)
{
    for (int i = 0; i < 16; ++i)
        state[i] ^= rk[i];
}

/* ---------------------------------------------------------------- *
 *  Very simple key‑schedule – generate 13 round keys by rotating the
 *  master key.  This is **not** the official ARIA schedule but keeps the
 *  code self‑contained and respects the constraints.
 * ---------------------------------------------------------------- */
void generateRoundKeys(const std::vector<int>& masterKey,
                       std::vector< std::vector<int> >& roundKeys)
{
    // masterKey length = 32 bytes (256 bit)
    for (int r = 0; r < 13; ++r)
    {
        std::vector<int> rk(16);
        int offset = (r * 4) % 32;               // rotate by 4 bytes each round
        for (int i = 0; i < 16; ++i)
            rk[i] = masterKey[(offset + i) % 32];
        roundKeys.push_back(rk);
    }
}

/* ---------------------------------------------------------------- *
 *  Encrypt a single 16‑byte block with the generated round keys.
 * ---------------------------------------------------------------- */
void encryptBlock(std::vector<int>& block,
                  const std::vector< std::vector<int> >& roundKeys)
{
    // 12 full rounds
    for (int round = 0; round < 12; ++round)
    {
        // 1. Substitution – alternate S‑boxes
        substitute(block, round % 2 == 0);

        // 2. Diffusion
        diffuse(block);

        // 3. Add round key
        addRoundKey(block, roundKeys[round]);
    }

    // Final round (only substitution + final key addition)
    substitute(block, 1);                 // use S‑box 2 for the final step
    addRoundKey(block, roundKeys[12]);    // last round key
}

/* ---------------------------------------------------------------- *
 *  CBC mode encryption for an arbitrary‑length plaintext.
 * ---------------------------------------------------------------- */
std::vector<int> cbcEncrypt(const std::vector<int>& plain,
                            const std::vector<int>& masterKey,
                            const std::vector<int>& iv)
{
    std::vector< std::vector<int> > roundKeys;
    generateRoundKeys(masterKey, roundKeys);

    std::vector<int> cipher;
    std::vector<int> prevBlock = iv;      // start with the IV

    int blocks = (int)plain.size() / 16;
    for (int b = 0; b < blocks; ++b)
    {
        // 1. Load one block
        std::vector<int> blk(16);
        for (int i = 0; i < 16; ++i)
            blk[i] = plain[b * 16 + i];

        // 2. XOR with previous ciphertext (CBC chaining)
        for (int i = 0; i < 16; ++i)
            blk[i] ^= prevBlock[i];

        // 3. Encrypt the block
        encryptBlock(blk, roundKeys);

        // 4. Append to result and set up chaining for next block
        for (int i = 0; i < 16; ++i) cipher.push_back(blk[i]);
        prevBlock = blk;
    }
    return cipher;
}

/* ---------------------------------------------------------------- *
 *  Main – generate deterministic structured key, IV, plaintext and display results.
 * ---------------------------------------------------------------- */
int main()
{
    // 1. Deterministic 256‑bit key: ascending values 0‑31
    std::vector<int> key(32);
    for (int i = 0; i < 32; ++i) key[i] = i;

    // 2. Deterministic IV: repeating pattern 0,1,2,3,...
    std::vector<int> iv(16);
    for (int i = 0; i < 16; ++i) iv[i] = (i * 2) % 256;

    // 3. Structured plaintext: 4 blocks (64 bytes) with ascending values 0‑63
    std::vector<int> plaintext(64);
    for (int i = 0; i < 64; ++i) plaintext[i] = i;

    // 4. Show the generated data
    printHex(key,       "Deterministic 256‑bit key:\n");
    printHex(iv,        "Deterministic IV (CBC):\n");
    printHex(plaintext, "Plaintext (64 bytes, ascending):\n");

    // 5. Perform CBC encryption
    std::vector<int> ciphertext = cbcEncrypt(plaintext, key, iv);

    // 6. Output the ciphertext
    printHex(ciphertext, "Ciphertext (CBC‑encrypted):\n");

    return 0;
}
