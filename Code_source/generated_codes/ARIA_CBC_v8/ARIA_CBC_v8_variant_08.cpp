// -----------------------------------------------------------------
// Helper: multiply in GF(2^8) with the AES polynomial 0x11b
// -----------------------------------------------------------------
int gfMul(int a, int b)
{
    int result = 0;
    int i = 0;
    while (i < 8)
    {
        if (b & 1) result ^= a;
        int hi = a & 0x80;
        a <<= 1;
        if (hi) a ^= 0x11b;
        b >>= 1;
        i = i + 1;
    }
    return result & 0xff;
}

// -----------------------------------------------------------------
// Linear diffusion layer (ARIA uses a fixed matrix)
// -----------------------------------------------------------------
void diffusion(std::vector<int> &state)
{
    std::vector<int> tmp(16);
    int i = 0;
    while (i < 16)
    {
        int a0 = state[i];
        int a1 = state[(i + 4) % 16];
        int a2 = state[(i + 8) % 16];
        int a3 = state[(i + 12) % 16];

        int b0 = gfMul(a0, 2) ^ gfMul(a1, 2) ^ gfMul(a2, 4) ^ gfMul(a3, 6);
        int b1 = gfMul(a0, 6) ^ gfMul(a1, 2) ^ gfMul(a2, 2) ^ gfMul(a3, 4);
        int b2 = gfMul(a0, 4) ^ gfMul(a1, 6) ^ gfMul(a2, 2) ^ gfMul(a3, 2);
        int b3 = gfMul(a0, 2) ^ gfMul(a1, 4) ^ gfMul(a2, 6) ^ gfMul(a3, 2);

        tmp[i]          = b0;
        tmp[(i + 4) %16] = b1;
        tmp[(i + 8) %16] = b2;
        tmp[(i +12) %16] = b3;

        i = i + 4;
    }
    state = tmp;
}

// -----------------------------------------------------------------
// Substitution layer – choose S‑box based on round parity
// -----------------------------------------------------------------
void substitution(std::vector<int> &state, bool useS1)
{
    int idx = 0;
    while (idx < 16)
    {
        if (useS1)
            state[idx] = sBox[state[idx]];
        else
            state[idx] = invSBox[state[idx]];
        idx = idx + 1;
    }
}

// -----------------------------------------------------------------
// Generate round keys for a 128‑bit key (12 rounds + final)
// -----------------------------------------------------------------
std::vector< std::vector<int> > keySchedule(const std::vector<int> &masterKey)
{
    std::vector< std::vector<int> > roundKeys;
    int r = 0;
    while (r < 13)
    {
        std::vector<int> rk(16);
        int i = 0;
        while (i < 16)
        {
            rk[i] = masterKey[(i + r) % 16];
            i = i + 1;
        }
        roundKeys.push_back(rk);
        r = r + 1;
    }
    return roundKeys;
}

// -----------------------------------------------------------------
// Encrypt a single 16‑byte block with ARIA (simplified)
// -----------------------------------------------------------------
std::vector<int> encryptBlock(const std::vector<int> &plain,
                              const std::vector< std::vector<int> > &roundKeys)
{
    std::vector<int> state = plain;

    int i = 0;
    while (i < 16)
    {
        state[i] ^= roundKeys[0][i];
        i = i + 1;
    }

    int round = 1;
    while (round <= 12)
    {
        bool useS1 = (round % 2 == 1);
        substitution(state, useS1);
        diffusion(state);
        i = 0;
        while (i < 16)
        {
            state[i] ^= roundKeys[round][i];
            i = i + 1;
        }
        round = round + 1;
    }

    substitution(state, false);
    i = 0;
    while (i < 16)
    {
        state[i] ^= roundKeys[12][i];
        i = i + 1;
    }

    return state;
}

// -----------------------------------------------------------------
// CBC mode encryption (handles padding)
// -----------------------------------------------------------------
std::vector<int> cbcEncrypt(const std::vector<int> &plain,
                            const std::vector<int> &key,
                            const std::vector<int> &iv)
{
    int padLen = 16 - (plain.size() % 16);
    std::vector<int> padded = plain;
    int p = 0;
    while (p < padLen)
    {
        padded.push_back(padLen);
        p = p + 1;
    }

    std::vector< std::vector<int> > rKeys = keySchedule(key);

    std::vector<int> cipher;
    std::vector<int> prev = iv;
    int offset = 0;
    while (offset < (int)padded.size())
    {
        std::vector<int> block(16);
        int j = 0;
        while (j < 16)
        {
            block[j] = padded[offset + j] ^ prev[j];
            j = j + 1;
        }

        std::vector<int> enc = encryptBlock(block, rKeys);
        int k = 0;
        while (k < 16)
        {
            cipher.push_back(enc[k]);
            k = k + 1;
        }
        prev = enc;
        offset = offset + 16;
    }
    return cipher;
}

// -----------------------------------------------------------------
// Helper: print a vector of bytes as hex
// -----------------------------------------------------------------
void printHex(const std::vector<int> &data)
{
    int i = 0;
    while (i < (int)data.size())
    {
        std::cout << std::hex << std::setw(2) << std::setfill('0')
                  << (data[i] & 0xff);
        if ((i + 1) % 16 == 0) std::cout << "\n";
        else std::cout << " ";
        i = i + 1;
    }
    std::cout << std::dec;
}

