int main()
{
    /* LLM input variant 1: minimal-boundary */
    // Minimal key: all zeros
    std::vector<int> key(16, 0x00);

    // Minimal IV: all zeros
    std::vector<int> iv(16, 0x00);

    // Single minimal test vector: one zero byte
    std::vector< std::vector<int> > tests;
    tests.push_back(std::vector<int>(1, 0x00));

    // Process each test vector
    int t = 0;
    while (t < (int)tests.size())
    {
        std::cout << "=== Test case " << t << " ===" << std::endl;
        print_hex(tests[t], "Plaintext");
        std::vector<int> cipher = cfb8_encrypt(tests[t], key, iv);
        print_hex(cipher, "Ciphertext");
        std::cout << std::endl;
        t = t + 1;
    }

    return 0;
}
