// ---------------------------------------------------------------
// Helper functions
// ---------------------------------------------------------------

// XOR two vectors of equal length (in‑place)
void xor_vec(std::vector<int>& a, const std::vector<int>& b)
{
    int i = 0;
    while (i < (int)a.size())
    {
        a[i] = a[i] ^ b[i];
        i = i + 1;
    }
}

// Simple linear diffusion (reordered arithmetic)
void linear_transform(std::vector<int>& blk)
{
    int i = 0;
    while (i < 16)
    {
        int left  = blk[(i + 1) & 15];
        int right = blk[(i + 2) & 15];
        // reorder: multiplication before addition
        int mixed = ((left << 1) & 0xFF) ^ ((right >> 1) & 0xFF);
        blk[i] = (blk[i] ^ mixed) & 0xFF;
        i = i + 1;
    }
}

// Substitution layer – uses S1 for every byte (for demo)
void substitute(std::vector<int>& blk)
{
    int i = 0;
    while (i < 16)
    {
        blk[i] = S1[blk[i]];
        i = i + 1;
    }
}

// One encryption round (substitution → linear → round‑key XOR)
void round_func(std::vector<int>& state, const std::vector<int>& rkey)
{
    substitute(state);
    linear_transform(state);
    xor_vec(state, rkey);
}

// ---------------------------------------------------------------
// Key schedule – creates 13 round keys (12 rounds + final)
// Very simplified: each round key is the original key rotated.
// ---------------------------------------------------------------
std::vector< std::vector<int> > expand_key(const std::vector<int>& key)
{
    std::vector< std::vector<int> > rkeys;
    int round = 0;
    while (round < 13)
    {
        std::vector<int> rk(16);
        int i = 0;
        while (i < 16)
        {
            // rotate key bytes by round amount (reordered ops)
            int src = (i + round) % 16;
            rk[i] = key[src];
            i = i + 1;
        }
        rkeys.push_back(rk);
        round = round + 1;
    }
    return rkeys;
}

// ---------------------------------------------------------------
// Encrypt a single 16‑byte block with the generated round keys.
// ---------------------------------------------------------------
std::vector<int> encrypt_block(const std::vector<int>& plain,
                               const std::vector< std::vector<int> >& rkeys)
{
    std::vector<int> state = plain; // copy (allowed)
    int r = 0;
    while (r < 12)          // 12 rounds for 128‑bit key
    {
        round_func(state, rkeys[r]);
        r = r + 1;
    }
    // final XOR with round key 12
    xor_vec(state, rkeys[12]);
    return state;
}

// ---------------------------------------------------------------
// CFB‑8 mode encryption (byte‑wise)
// ---------------------------------------------------------------
std::vector<int> cfb8_encrypt(const std::vector<int>& pt,
                              const std::vector<int>& key,
                              const std::vector<int>& iv)
{
    std::vector< std::vector<int> > rkeys = expand_key(key);
    std::vector<int> reg = iv;               // shift register (16 bytes)
    std::vector<int> ct;
    int idx = 0;
    while (idx < (int)pt.size())
    {
        std::vector<int> enc = encrypt_block(reg, rkeys);
        int out = (enc[0] ^ pt[idx]) & 0xFF; // use first byte of encrypted register
        ct.push_back(out);
        // shift register left by one byte, append ciphertext byte
        int i = 0;
        while (i < 15)
        {
            reg[i] = reg[i + 1];
            i = i + 1;
        }
        reg[15] = out;
        idx = idx + 1;
    }
    return ct;
}

// ---------------------------------------------------------------
// Utility: print a byte vector as hex
// ---------------------------------------------------------------
void print_hex(const std::vector<int>& data, const char* title)
{
    std::cout << title << ": ";
    int i = 0;
    while (i < (int)data.size())
    {
        std::cout << std::hex << std::setw(2) << std::setfill('0')
                  << (data[i] & 0xFF) << " ";
        i = i + 1;
    }
    std::cout << std::dec << std::endl;
}

