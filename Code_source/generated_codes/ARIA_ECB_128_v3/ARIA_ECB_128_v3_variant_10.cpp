/* ------------------------------------------------------------------
 *  Galois field multiplication tables for the diffusion matrix.
 * ------------------------------------------------------------------ */
static int M4[256];
static int M6[256];
static int M7[256];

/* ------------------------------------------------------------------
 *  Helper: multiply a byte by 0x02 in GF(2^8) with the ARIA polynomial
 * ------------------------------------------------------------------ */
static int xtime(int x) {
    int hi = x & 0x80;
    x = (x << 1) & 0xff;
    if (hi) x ^= 0x1b;
    return x;
}

/* ------------------------------------------------------------------
 *  Initialise the multiplication tables (run once at start)
 * ------------------------------------------------------------------ */
static void initMulTables() {
    for (int i = 0; i < 256; ++i) {
        int x2 = xtime(i);
        int x4 = xtime(x2);
        int x8 = xtime(x4);
        M4[i] = x4;
        M6[i] = x4 ^ x2;
        M7[i] = x4 ^ x2 ^ i;
    }
}

/* ------------------------------------------------------------------
 *  Linear diffusion (matrix M) – manual unrolled for 4 words
 * ------------------------------------------------------------------ */
static void diffusion(const std::vector<int>& src, std::vector<int>& dst) {
    int w0 = (src[0] << 24) | (src[1] << 16) | (src[2] << 8) | src[3];
    int w1 = (src[4] << 24) | (src[5] << 16) | (src[6] << 8) | src[7];
    int w2 = (src[8] << 24) | (src[9] << 16) | (src[10] << 8) | src[11];
    int w3 = (src[12] << 24) | (src[13] << 16) | (src[14] << 8) | src[15];

    int out0 = 0, out1 = 0, out2 = 0, out3 = 0;
    for (int i = 0; i < 4; ++i) {
        int b0 = (w0 >> (24 - 8 * i)) & 0xff;
        int b1 = (w1 >> (24 - 8 * i)) & 0xff;
        int b2 = (w2 >> (24 - 8 * i)) & 0xff;
        int b3 = (w3 >> (24 - 8 * i)) & 0xff;

        int c0 = b0 ^ M4[b1] ^ M6[b2] ^ M7[b3];
        int c1 = M7[b0] ^ b1 ^ M4[b2] ^ M6[b3];
        int c2 = M6[b0] ^ M7[b1] ^ b2 ^ M4[b3];
        int c3 = M4[b0] ^ M6[b1] ^ M7[b2] ^ b3;

        out0 = (out0 << 8) | c0;
        out1 = (out1 << 8) | c1;
        out2 = (out2 << 8) | c2;
        out3 = (out3 << 8) | c3;
    }

    dst[0] = (out0 >> 24) & 0xff; dst[1] = (out0 >> 16) & 0xff;
    dst[2] = (out0 >> 8) & 0xff;  dst[3] = out0 & 0xff;
    dst[4] = (out1 >> 24) & 0xff; dst[5] = (out1 >> 16) & 0xff;
    dst[6] = (out1 >> 8) & 0ff;    dst[7] = out1 & 0xff;
    dst[8] = (out2 >> 24) & 0xff; dst[9] = (out2 >> 16) & 0xff;
    dst[10] = (out2 >> 8) & 0xff; dst[11] = out2 & 0xff;
    dst[12] = (out3 >> 24) & 0xff; dst[13] = (out3 >> 16) & 0xff;
    dst[14] = (out3 >> 8) & 0ff;   dst[15] = out3 & 0xff;
}

