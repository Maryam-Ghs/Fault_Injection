/* For SB3 and SB4 we simply reuse SB1 and SB2 – this keeps the
   implementation short while still exercising four distinct
   substitution steps.                                           */
static int SB3[256];
static int SB4[256];

/* ---------------------------------------------------------------- *
 *  Helper: multiplication by 2 in GF(2^8) (used by diffusion)
 * ---------------------------------------------------------------- */
int mul2(int x)
{
    int y = (x << 1) & 0xff;
    if (x & 0x80) y ^= 0x1b;
    return y;
}

/* ---------------------------------------------------------------- *
 *  Diffusion layer (linear transformation)
 * ---------------------------------------------------------------- */
void diffusion(int s[16])
{
    int tmp[16];
    for (int col = 0; col < 4; ++col)
    {
        int a0 = s[col];
        int a1 = s[4 + col];
        int a2 = s[8 + col];
        int a3 = s[12 + col];

        int b0 = mul2(a0) ^ mul2(a1) ^ mul2(a2) ^ mul2(a3);
        int b1 = a0 ^ a1 ^ a2 ^ a3;
        int b2 = a0 ^ a1 ^ a2 ^ a3;
        int b3 = mul2(a0) ^ mul2(a1) ^ mul2(a2) ^ mul2(a3);

        tmp[col]      = b0;
        tmp[4 + col]  = b1;
        tmp[8 + col]  = b2;
        tmp[12 + col] = b3;
    }
    for (int i = 0; i < 16; ++i) s[i] = tmp[i];
}

/* ---------------------------------------------------------------- *
 *  Substitution layer – the order of S‑boxes depends on the round.
 * ---------------------------------------------------------------- */
void substitute(int s[16], int round)
{
    for (int i = 0; i < 16; ++i)
    {
        int idx = i & 3;
        int val = s[i];
        if (round % 2 == 0)
        {
            if (idx == 0) s[i] = SB1[val];
            else if (idx == 1) s[i] = SB2[val];
            else if (idx == 2) s[i] = SB3[val];
            else               s[i] = SB4[val];
        }
        else
        {
            if (idx == 0) s[i] = SB3[val];
            else if (idx == 1) s[i] = SB4[val];
            else if (idx == 2) s[i] = SB1[val];
            else               s[i] = SB2[val];
        }
    }
}

/* ---------------------------------------------------------------- *
 *  Add round key (XOR)
 * ---------------------------------------------------------------- */
void add_round_key(int s[16], const int rk[16])
{
    for (int i = 0; i < 16; ++i) s[i] ^= rk[i];
}

/* ---------------------------------------------------------------- *
 *  Very small key schedule – rotates the master key and XORs a
 *  round‑dependent constant.  It produces 13 round keys (12 rounds
 *  + final whitening) for a 128‑bit key.
 * ---------------------------------------------------------------- */
void key_schedule(const int master[16], int round_key[13][16])
{
    int rc[13][16];
    for (int r = 0; r < 13; ++r)
        for (int i = 0; i < 16; ++i)
            rc[r][i] = (r * 0x11 + i) & 0xff;

    for (int i = 0; i < 16; ++i) round_key[0][i] = master[i];

    for (int r = 1; r < 13; ++r)
    {
        for (int i = 0; i < 16; ++i)
            round_key[r][i] = round_key[r-1][(i+1)%16] ^ rc[r][i];
    }
}

/* ---------------------------------------------------------------- *
 *  Encrypt a single 16‑byte block (ECB mode)
 * ---------------------------------------------------------------- */
void encrypt_block(const int pt[16], int ct[16],
                   const int round_key[13][16])
{
    int state[16];
    for (int i = 0; i < 16; ++i) state[i] = pt[i];

    for (int r = 0; r < 12; ++r)
    {
        add_round_key(state, round_key[r]);
        substitute(state, r);
        diffusion(state);
    }
    add_round_key(state, round_key[12]);

    for (int i = 0; i < 16; ++i) ct[i] = state[i];
}

/* ---------------------------------------------------------------- *
 *  Helper: print a 16‑byte block as hex
 * ---------------------------------------------------------------- */
void print_hex(const int block[16])
{
    for (int i = 0; i < 16; ++i)
        std::cout << std::hex << std::setw(2) << std::setfill('0')
                  << (block[i] & 0xff);
    std::cout << std::dec << std::endl;
}

/* ---------------------------------------------------------------- *
 *  Main – deterministic test vector
 * ---------------------------------------------------------------- */
int main()
{
    for (int i = 0; i < 256; ++i)
    {
        SB3[i] = SB1[i];
        SB4[i] = SB2[i];
    }

    // key: alternating 0 and 1
    int key[16];
    for (int i = 0; i < 16; ++i) key[i] = i % 2;

    // plaintext: all zeros
    int plain[16];
    for (int i = 0; i < 16; ++i) plain[i] = 0;

    int rkey[13][16];
    key_schedule(key, rkey);

    int cipher[16];
    encrypt_block(plain, cipher, rkey);

    std::cout << "Key      : ";  print_hex(key);
    std::cout << "Plaintext: ";  print_hex(plain);
    std::cout << "Ciphertext: "; print_hex(cipher);

    return 0;
}
