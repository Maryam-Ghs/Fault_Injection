/* -------------------------------------------------------------
 * Simple left‑rotate for 32‑bit integers (sign‑extension is ignored)
 * ------------------------------------------------------------- */
int rotl32(int value, int shift) {
    int left  = value << shift;
    int right = value >> (32 - shift);
    return left | right;
}

