/* -------------------------------------------------------------
 * Round constants for 128‑bit key (12 rounds + 1 whitening)
 * ------------------------------------------------------------- */
int RC[13] = {
    0x517cc1b7, 0x27220a94, 0xfe13abe8,
    0x98a2ec1d, 0x2f6a764d, 0x2d8c2dfe,
    0x2e2843c3, 0x8a4ae79d, 0x8d2c6d3b,
    0xf5c6a1f0, 0x8c0e9c7b, 0x5c2c9f13,
    0x345f4c57
};

/* -------------------------------------------------------------
 * ARIA ECB class – all data lives on the stack
 * ------------------------------------------------------------- */
class ARIA_ECB {
    int roundKey[13][4];

    void scheduleKey(const int *userKey) {
        roundKey[0][0] = userKey[0];
        roundKey[0][1] = userKey[1];
        roundKey[0][2] = userKey[2];
        roundKey[0][3] = userKey[3];

        int i = 1;
        while (i <= 12) {
            int tmp0 = roundKey[i-1][0];
            int tmp1 = roundKey[i-1][1];
            int tmp2 = roundKey[i-1][2];
            int tmp3 = roundKey[i-1][3];

            int rot0 = rotl32(tmp0, 1);
            int rot1 = rotl32(tmp1, 1);
            int rot2 = rotl32(tmp2, 1);
            int rot3 = rotl32(tmp3, 1);

            roundKey[i][0] = rot0 ^ RC[i-1];
            roundKey[i][1] = rot1 ^ RC[i-1];
            roundKey[i][2] = rot2 ^ RC[i-1];
            roundKey[i][3] = rot3 ^ RC[i-1];

            i = i + 1;
        }
    }

    void subBytesS1(int *state) {
        int idx = 0;
        while (idx < 4) {
            int w = state[idx];
            int b0 = (w >> 24) & 0xFF;
            int b1 = (w >> 16) & 0xFF;
            int b2 = (w >> 8)  & 0xFF;
            int b3 =  w        & 0xFF;

            int sb0 = SBOX1[b0];
            int sb1 = SBOX1[b1];
            int sb2 = SBOX1[b2];
            int sb3 = SBOX1[b3];

            int neww = (sb0 << 24) | (sb1 << 16) | (sb2 << 8) | sb3;
            state[idx] = neww;
            idx = idx + 1;
        }
    }

    void subBytesS2(int *state) {
        int idx = 0;
        while (idx < 4) {
            int w = state[idx];
            int b0 = (w >> 24) & 0xFF;
            int b1 = (w >> 16) & 0xFF;
            int b2 = (w >> 8)  & 0xFF;
            int b3 =  w        & 0xFF;

            int sb0 = SBOX2[b0];
            int sb1 = SBOX2[b1];
            int sb2 = SBOX2[b2];
            int sb3 = SBOX2[b3];

            int neww = (sb0 << 24) | (sb1 << 16) | (sb2 << 8) | sb3;
            state[idx] = neww;
            idx = idx + 1;
        }
    }

    void diffusion(int *state) {
        int tmp[4];
        int i = 0;
        while (i < 4) {
            int a = state[i];
            int b = state[(i+1) & 3];
            int c = state[(i+2) & 3];
            int d = state[(i+3) & 3];

            int rotb = rotl32(b, 1);
            int rotc = rotl32(c, 5);
            int rotd = rotl32(d, 2);

            tmp[i] = a ^ rotb ^ rotc ^ rotd;
            i = i + 1;
        }
        i = 0;
        while (i < 4) {
            state[i] = tmp[i];
            i = i + 1;
        }
    }

    void round(int *state, const int *rk, int roundNo) {
        if ((roundNo & 1) == 1) {
            subBytesS1(state);
        } else {
            subBytesS2(state);
        }
        diffusion(state);
        int i = 0;
        while (i < 4) {
            state[i] ^= rk[i];
            i = i + 1;
        }
    }

public:
    void encryptBlock(const int *plain, int *cipher, const int *key) {
        scheduleKey(key);
        int state[4];
        int i = 0;
        while (i < 4) {
            state[i] = plain[i];
            i = i + 1;
        }
        i = 0;
        while (i < 4) {
            state[i] ^= roundKey[0][i];
            i = i + 1;
        }
        int r = 1;
        while (r <= 12) {
            round(state, roundKey[r], r);
            r = r + 1;
        }
        i = 0;
        while (i < 4) {
            state[i] ^= roundKey[0][i];
            i = i + 1;
        }
        i = 0;
        while (i < 4) {
            cipher[i] = state[i];
            i = i + 1;
        }
    }
};

void printHexBlock(const int *block) {
    int i = 0;
    while (i < 4) {
        int w = block[i];
        int b0 = (w >> 24) & 0xFF;
        int b1 = (w >> 16) & 0xFF;
        int b2 = (w >> 8)  & 0xFF;
        int b3 =  w        & 0xFF;
        printf("%02x%02x%02x%02x ", b0, b1, b2, b3);
        i = i + 1;
    }
    printf("\n");
}

