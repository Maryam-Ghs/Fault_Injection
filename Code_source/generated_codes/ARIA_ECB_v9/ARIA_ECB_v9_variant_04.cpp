int mul_gf(int a, int b) {
    int p = 0;
    int hi_bit_set;
    int i = 0;
    while (i < 8) {
        if ((b & 1) != 0) p ^= a;
        hi_bit_set = a & 0x80;
        a <<= 1;
        if (hi_bit_set != 0) a ^= 0x11b;
        b >>= 1;
        ++i;
    }
    return p & 0xFF;
}

void diffuse(int out[16], const int in[16]) {
    int tmp[16];
    for (int col = 0; col < 4; ++col) {
        int i0 = in[col];
        int i1 = in[4 + col];
        int i2 = in[8 + col];
        int i3 = in[12 + col];
        tmp[col]      = mul_gf(i0, 2) ^ mul_gf(i1, 3) ^ i2 ^ i3;
        tmp[4 + col]  = i0 ^ mul_gf(i1, 2) ^ mul_gf(i2, 3) ^ i3;
        tmp[8 + col]  = i0 ^ i1 ^ mul_gf(i2, 2) ^ mul_gf(i3, 3);
        tmp[12 + col] = mul_gf(i0, 3) ^ i1 ^ i2 ^ mul_gf(i3, 2);
    }
    for (int i = 0; i < 16; ++i) out[i] = tmp[i];
}

void substitute(int out[16], const int in[16], int roundIdx) {
    int tmp[16];
    int useFirst = (roundIdx & 1);
    for (int i = 0; i < 16; ++i) {
        if (useFirst) tmp[i] = sbox1[in[i]];
        else          tmp[i] = sbox2[in[i]];
    }
    for (int i = 0; i < 16; ++i) out[i] = tmp[i];
}

void addRoundKey(int out[16], const int in[16], const int rk[16]) {
    int tmp[16];
    for (int i = 0; i < 16; ++i) tmp[i] = in[i] ^ rk[i];
    for (int i = 0; i < 16; ++i) out[i] = tmp[i];
}

void scheduleKeys(int master[16], int rkeys[13][16]) {
    for (int i = 0; i < 16; ++i) rkeys[0][i] = master[i];
    for (int r = 1; r <= 12; ++r) {
        for (int i = 0; i < 16; ++i) {
            int rot = master[(i + r) % 16];
            int rc  = (r * 0x5A) & 0xFF;
            rkeys[r][i] = rot ^ rc;
        }
    }
}

void encryptBlock(int out[16], const int in[16], int rkeys[13][16]) {
    int state[16];
    int temp[16];
    addRoundKey(state, in, rkeys[0]);
    int round = 1;
    while (round <= 11) {
        substitute(temp, state, round);
        diffuse(state, temp);
        addRoundKey(state, state, rkeys[round]);
        ++round;
    }
    substitute(temp, state, round);
    addRoundKey(out, temp, rkeys[12]);
}

void printHex(const char *label, const int *blk, int len) {
    std::printf("%s", label);
    for (int i = 0; i < len; ++i) std::printf("%02X", blk[i] & 0xFF);
    std::printf("\n");
}

