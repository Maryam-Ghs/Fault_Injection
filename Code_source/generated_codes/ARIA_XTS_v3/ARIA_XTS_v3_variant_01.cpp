// ------------------------------------------------------------
// Helper: print a byte array as hex
// ------------------------------------------------------------
void printHex(const int *buf, int len) {
    for (int i = 0; i < len; ++i) {
        std::cout << std::hex << std::setw(2) << std::setfill('0')
                  << (buf[i] & 0xFF);
    }
    std::cout << std::dec << std::endl;
}

